// 房间模板：30 × 17 格。生成器会随机挑选、随机镜像，并按连通关系开凿出入口。
//
//  #  实心岩石        .  空气           =  单向平台（可从下方跳上）
//  ^  尖刺            ?  50% 概率为岩石
//  e  地面敌人位      g  盾卫优先位     f  飞行敌人位
//  $  遗骸（余烬宝箱）S  灯龛候选位     P  出生点     L  背景吊灯
//
// 障碍的设计原则：挡在路上的东西都要给玩家选择。
//  - 悬在地面上方、底下留一格空隙的石块 = 「跳过去，或者蹲着钻过去」。
//    一格空隙只有下蹲的玩家能过，持铲的僧人、持盾的钟卫都过不去——钻洞也是甩掉追兵的办法。
//  - 实心的台阶 / 高台只用来造落差和掩体，不横在唯一的通路上当墙。
//
// 约定：左右出入口位于第 11–14 行，上下出入口位于第 12–17 列，
// 所以这些区域不要放会堵路的岩石；尖刺不要放在第 11–18 列（防止从上方掉进来直接落刺）。

